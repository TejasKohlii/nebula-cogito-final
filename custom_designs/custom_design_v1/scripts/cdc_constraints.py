#!/usr/bin/env python3
"""Resolve mapped Nangate45 DFF endpoint pins for narrow CDC constraints."""
import argparse, json, pathlib
parser=argparse.ArgumentParser()
parser.add_argument('--netlist',default='build/benchmark_mapped.json')
parser.add_argument('--outdir',default='build')
args=parser.parse_args()
outdir=pathlib.Path(args.outdir)
outdir.mkdir(parents=True,exist_ok=True)
mods = json.loads(pathlib.Path(args.netlist).read_text())['modules']
m = mods['mailbox']
def pins(net, direction):
    bits=set(m['netnames'][net]['bits'])
    result=[]
    for name,c in m['cells'].items():
        # Deliberately fail for unrecognized technology instead of cutting logic.
        if c['type'] not in ('DFF_X1','DFF_X2','DFFR_X1','DFFR_X2','DFFS_X1','DFFS_X2'): continue
        if bits.intersection(c['connections'].get('Q',[])):
            result.append(name+'/'+direction)
    assert len(result)==len(bits), (net,result)
    return result
lines=['# Generated by scripts/cdc_constraints.py; Nangate45 mapping.']
for i in range(5):
    def get(net,direction):
        if direction == 'Q':
            return '[get_cells {'+' '.join(f'domain[{i}].cdc/{p.rsplit(chr(47),1)[0]}' for p in pins(net,direction))+'}]'
        return '[get_pins {'+' '.join(f'domain[{i}].cdc/{p}' for p in pins(net,direction))+'}]'
    for src,dst in [('req','req_meta'),('ack','ack_meta')]:
        lines.append(f'set_false_path -from {get(src,"Q")} -to {get(dst,"D")}')
    # Payload is held for a complete request/ack round trip. Restrict flight time
    # below one destination master cycle, well before synchronized capture.
    period=[1, 0.833333333,1.25,1.538461538,2][(i+1)%5]
    lines.append(f'set_max_delay -ignore_clock_latency {0.8*period:.9f} -from {get("payload","Q")} -to {get("dst_data","D")}')
    lines.append(f'set_min_delay -ignore_clock_latency 0 -from {get("payload","Q")} -to {get("dst_data","D")}')
(outdir/'cdc_constraints.tcl').write_text('\n'.join(lines)+'\n')

# Put generated-clock definitions at their sink CK pins. Defining them at
# divider Q pins causes OpenSTA to lose data arrivals through the XOR feedback.
top = mods['benchmark']
sinks = {}
for i in range(5):
    for ratio in (2,4):
        sinks[('benchmark',top['ports'][f'gen{ratio}']['bits'][i])] = (i,ratio,[])
def descend(name, prefix, connected):
    mod=mods[name]
    def net(b):
        if isinstance(b,str): return ('constant',b)
        return connected.get(b,(prefix,b))
    for cname,c in mod.get('cells',{}).items():
        path=prefix+'/'+cname if prefix!='benchmark' else cname
        if 'CK' in c['connections'] and c['type'].startswith('DFF'):
            key=net(c['connections']['CK'][0])
            if key in sinks: sinks[key][2].append(path+'/CK')
        elif c['type'] in mods and not int(mods[c['type']].get('attributes',{}).get('blackbox','0'),2):
            sub=mods[c['type']]
            mapping={b:net(parent) for port,bits in c['connections'].items()
                     for b,parent in zip(sub['ports'][port]['bits'],bits)}
            descend(c['type'],path,mapping)
descend('benchmark','benchmark',{})
clock_lines=['# Generated clock sink pins resolved from mapped connectivity.']
for i,ratio,ps in sinks.values():
    assert ps, (i,ratio)
    clock_lines.append(f'set generated_clock_pins({i},{ratio}) '+'{'+' '.join(sorted(ps))+'}')
(outdir/'generated_clock_pins.tcl').write_text('\n'.join(clock_lines)+'\n')
