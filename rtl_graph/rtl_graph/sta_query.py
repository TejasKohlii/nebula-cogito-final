"""Run OpenSTA on the gate-level netlist and dump everything the graph needs:

  clocks.tsv      name, period, generated flag, source objects
  registers.tsv   every register instance: reference cell, output nets, clocks on its clock pin
  endpoints.tsv   worst max-delay path per endpoint: start/end pins, clocks, slack, arrival,
                  required, Q-pin arrival, Q->D combinational delay
  critical.json   report_checks -format json for the K worst paths of every path group
  violating.json  report_checks -format json for every violating endpoint (point-level detail)
  units.txt       report_units output (time unit of the TSV numbers)
"""
from __future__ import annotations

import os
import shlex
import subprocess
import tempfile
from pathlib import Path
from typing import List, Optional

REGISTERS_TCL = r"""
# ---- registers ----
# instance -> output nets (via all_registers -output_pins) and clocks on clock pins
array set qnets {}
foreach op [all_registers -output_pins] {
  set n [get_nets -of_objects $op]
  if {$n == ""} { continue }
  set full [get_full_name $op]
  set inst [string range $full 0 [expr {[string last / $full] - 1}]]
  lappend qnets($inst) "[get_name $op]=[get_full_name $n]"
}
array set rclocks {}
foreach cp [all_registers -clock_pins] {
  set full [get_full_name $cp]
  set inst [string range $full 0 [expr {[string last / $full] - 1}]]
  foreach c [get_property $cp clocks] { lappend rclocks($inst) [get_name $c] }
}
set fp [open $out/registers.tsv w]
puts $fp "instance\tref\tq_nets\tclocks"
foreach inst [all_registers -cells] {
  set name [get_full_name $inst]
  set q {}; if {[info exists qnets($name)]} { set q $qnets($name) }
  set c {}; if {[info exists rclocks($name)]} { set c [lsort -unique $rclocks($name)] }
  puts $fp "$name\t[get_property $inst ref_name]\t[join $q ,]\t[join $c ,]"
}
close $fp

"""

TCL_TEMPLATE = r"""
# ---- generated by rtl_graph.sta_query ----
foreach lib {__LIBS__} { read_liberty $lib }
foreach v {__NETLISTS__} { read_verilog $v }
link_design __TOP__
read_sdc __SDC__
__EXTRA__
set out __OUT__
set fpu [open $out/units.txt w]
puts $fpu "time_unit [sta::unit_scale time] [sta::unit_suffix time]"
close $fpu

# ---- clocks ----
set fp [open $out/clocks.tsv w]
puts $fp "name\tperiod\tgenerated\tsources"
foreach clk [all_clocks] {
  set srcs {}
  foreach s [get_property $clk sources] { lappend srcs [get_full_name $s] }
  puts $fp "[get_name $clk]\t[get_property $clk period]\t[get_property $clk is_generated]\t[join $srcs ,]"
}
close $fp

__REGISTERS__
# ---- worst path per endpoint ----
set paths [find_timing_paths -path_delay max -group_path_count 100000000 -endpoint_path_count 1 __SLACK_MAX__]
set fp [open $out/endpoints.tsv w]
puts $fp "endpoint\tstartpoint\tlaunch_clock\tcapture_clock\tslack\tarrival\trequired\tq_arrival\tcomb_delay\tnpoints"
foreach p $paths {
  set ep [get_full_name [get_property $p endpoint]]
  set sp [get_full_name [get_property $p startpoint]]
  set lc ""; catch {set lc [get_name [get_property $p startpoint_clock]]}
  set cc ""; catch {set cc [get_name [get_property $p endpoint_clock]]}
  set slack [get_property $p slack]
  set pts [get_property $p points]
  set first [lindex $pts 0]; set last [lindex $pts end]
  set qa [get_property $first arrival]
  set arr [get_property $last arrival]
  set req [get_property $last required]
  puts $fp "$ep\t$sp\t$lc\t$cc\t$slack\t$arr\t$req\t$qa\t[expr {$arr - $qa}]\t[llength $pts]"
}
close $fp

# ---- critical paths (K worst per path group, full detail) ----
report_checks -path_delay max -group_path_count __K__ -endpoint_path_count 1 -format json -fields {capacitance slew} > $out/critical.json
# ---- every violating endpoint with full point detail (through-delay attribution) ----
report_checks -path_delay max -slack_max 0 -group_path_count 100000000 -endpoint_path_count 1 -format json -fields {capacitance slew} > $out/violating.json
# Include non-violating endpoints too: their logic still needs local delays.
report_checks -path_delay max -group_path_count 100000000 -endpoint_path_count 1 -format json -fields {capacitance slew} > $out/all_paths.json
report_checks -path_delay max -group_path_count 1 -endpoint_path_count 1 -format full_clock_expanded -fields {net} -digits 4 > $out/critical.rpt
puts "RTL_GRAPH_DONE paths=[llength $paths]"
exit
"""


def write_tcl(out_dir: str, libs: List[str], netlists: List[str], top: str, sdc: str,
              extra_tcl: Optional[List[str]] = None, critical_per_group: int = 10,
              only_violating: bool = False, dump_registers: bool = True) -> str:
    out_dir = str(Path(out_dir).absolute())
    Path(out_dir).mkdir(parents=True, exist_ok=True)
    def tcl_list(xs):
        return " ".join("{" + str(Path(x).absolute()) + "}" for x in xs)
    tcl = (TCL_TEMPLATE
           .replace("__LIBS__", tcl_list(libs))
           .replace("__NETLISTS__", tcl_list(netlists))
           .replace("__TOP__", top)
           .replace("__SDC__", "{" + str(Path(sdc).absolute()) + "}")
           .replace("__EXTRA__", "\n".join(extra_tcl or []))
           .replace("__OUT__", "{" + out_dir + "}")
           .replace("__K__", str(critical_per_group))
           .replace("__SLACK_MAX__", "-slack_max 0" if only_violating else "")
           .replace("__REGISTERS__", REGISTERS_TCL if dump_registers else "# (register dump skipped: netlist parsed in Python)"))
    path = os.path.join(out_dir, "rtl_graph_query.tcl")
    Path(path).write_text(tcl)
    return path


def run_query(out_dir: str, libs: List[str], netlists: List[str], top: str, sdc: str,
              sta: str = "sta", cwd: Optional[str] = None, extra_tcl: Optional[List[str]] = None,
              critical_per_group: int = 10, only_violating: bool = False, timeout: int = 7200,
              dump_registers: bool = True) -> str:
    """Run OpenSTA; returns out_dir.  cwd is where OpenSTA runs, so that
    `source`d helper files referenced relatively inside the SDC resolve.  Defaults to the current directory."""
    tcl = write_tcl(out_dir, libs, netlists, top, sdc, extra_tcl, critical_per_group, only_violating, dump_registers)
    cwd = cwd or os.getcwd()
    log = os.path.join(out_dir, "sta.log")
    # OpenSTA startup sourcing does not quote script paths containing spaces.
    with tempfile.TemporaryDirectory(prefix="cogito_sta_") as temporary, open(log, "w") as lf:
        startup = Path(temporary) / "query.tcl"
        startup.write_text(Path(tcl).read_text())
        r = subprocess.run([sta, "-no_init", "-exit", str(startup)], cwd=cwd, stdout=lf, stderr=subprocess.STDOUT,
                           text=True, timeout=timeout)
    text = open(log).read()
    if r.returncode != 0 or "RTL_GRAPH_DONE" not in text:
        raise RuntimeError(f"OpenSTA query failed (rc={r.returncode}); see {log}\n{text[-3000:]}")
    return out_dir
